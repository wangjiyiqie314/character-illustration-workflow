import {scratchDirectory} from './temp.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {choose} from '../tools/deliver.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const scratch=scratchDirectory(path.join(root,'tests'),'scratch-v3-');
const run=path.join(scratch,'trial');
const cli=(...args)=>spawnSync(process.execPath,[path.join(root,'tools','deliver.mjs'),'--run',run,...args],{cwd:root,encoding:'utf8'});
const recipe={schema_version:2,asset_id:'POSTAL_GIRL_V3',style_version:'STYLE_003',workflow:'direct_first',stage_order:['direct','lineart','flat','lighting','refine'],anchor_stages:['direct','lineart','flat'],planned_images:5,repair_limit:2,user_assessment:'TEST FIXTURE assessment',demo_authorization:'TEST FIXTURE explicit demo',candidates:[{id:'DIRECT_V3',stage:'direct',kind:'image',prompt:'fixture direct image',reference_specs:[]}]};
const recipePath=path.join(scratch,'recipe.json');fs.writeFileSync(recipePath,JSON.stringify(recipe));
const result=cli('init','--demo','--recipe',recipePath);assert.equal(result.status,0,result.stderr);
const state=JSON.parse(fs.readFileSync(path.join(run,'project.json'),'utf8'));
assert.equal(state.asset_id,recipe.asset_id);
assert.equal(state.style_version,recipe.style_version);
assert.equal(state.workflow,'direct_first');
assert.equal(state.user_assessment,recipe.user_assessment);
assert.equal(state.authorization,recipe.demo_authorization);
assert.deepEqual(state.anchor_stages,recipe.anchor_stages);
assert.equal(state.planned_images,5);
assert.equal(cli('prepare','DIRECT_V3').status,0);
state.artifacts.DIRECT_V3={...state.artifacts.DIRECT_V3,file:'fixture.png',sha256:'fixture',qa:{hard_fail:[],observations:[],structure_check:{status:'pass'}}};
choose(state,'direct','DIRECT_V3','fixture selection');
assert.equal(state.anchors.direct.id,'DIRECT_V3');
assert.equal(state.stages.direct.selection.selected_by,'agent_demo');
state.artifacts.FINAL_V3={id:'FINAL_V3',stage:'refine',file:'fixture.png',width:1024,height:1536,qa:null};
state.stages.refine.candidates=['FINAL_V3'];state.stages.refine.selection={id:'FINAL_V3',stale:false};
fs.writeFileSync(path.join(run,'project.json'),JSON.stringify(state));
const render=cli('render');assert.equal(render.status,0,render.stderr);
const html=fs.readFileSync(path.join(run,'index.html'),'utf8');
assert.ok(html.includes('同源比较'));
assert.ok(!html.includes('comparisons/V1_REFINE_A.png'),'v3 must not assume a v1 comparison file');
const reviewRun=path.join(scratch,'review');
const review=spawnSync(process.execPath,[path.join(root,'tools','deliver.mjs'),'--run',reviewRun,'init','--recipe',recipePath],{cwd:root,encoding:'utf8'});
assert.equal(review.status,0,review.stderr);
assert.equal(JSON.parse(fs.readFileSync(path.join(reviewRun,'project.json'),'utf8')).authorization,null);
const nobleRun=path.join(scratch,'new-character');
const nobleRecipe={...recipe,asset_id:'NOBLE_TEST',attributes:['黑发','金瞳','贵族小姐'],purpose:'白底立绘',retouch:'尚未人工修绘',user_v1_assessment:null};
const nobleRecipePath=path.join(scratch,'noble-recipe.json');fs.writeFileSync(nobleRecipePath,JSON.stringify(nobleRecipe));
const nobleInit=spawnSync(process.execPath,[path.join(root,'tools','deliver.mjs'),'--run',nobleRun,'init','--recipe',nobleRecipePath],{cwd:root,encoding:'utf8'});
assert.equal(nobleInit.status,0,nobleInit.stderr);
const nobleState=JSON.parse(fs.readFileSync(path.join(nobleRun,'project.json'),'utf8'));
assert.deepEqual(nobleState.attributes,nobleRecipe.attributes,'A new character must not inherit postal-girl attributes');
assert.equal(nobleState.purpose,nobleRecipe.purpose);assert.equal(nobleState.retouch,nobleRecipe.retouch);
assert.equal(nobleState.user_v1_assessment,null);assert.equal(nobleState.mode,'review');assert.equal(nobleState.authorization,null);
console.log('PASS: direct-first recipe metadata, configurable anchors, demo provenance, source comparison routing, review default');
