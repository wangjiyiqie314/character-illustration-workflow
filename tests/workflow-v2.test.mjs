import {scratchDirectory} from './temp.mjs';
import assert from 'node:assert/strict';
import * as workflow from '../tools/deliver.mjs';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const stages=['pose','structure','detail','scene','flat','lighting','refine'];
const fixture=()=>({schema_version:2,mode:'demo',stage_order:stages,stages:Object.fromEntries(stages.map(s=>[s,{candidates:[s.toUpperCase()],selection:null}])),artifacts:Object.fromEntries(stages.map(s=>[s.toUpperCase(),{id:s.toUpperCase(),stage:s,kind:'image',file:'fixture.png',sha256:s,stale:false,qa:{hard_fail:[],structure_check:{status:'pass'}}}]))});
const state=fixture();
workflow.ready(state,'pose');
workflow.choose(state,'pose','POSE','检查后锁定');
assert.throws(()=>workflow.ready(state,'detail'),/Previous stage/);
workflow.choose(state,'structure','STRUCTURE','结构成立');
state.artifacts.DETAIL.references=[{id:'POSE',role:'pose_anchor',sha256:'pose'},{id:'STRUCTURE',role:'edit_target',sha256:'structure'}];
workflow.validateReferences(state,state.artifacts.DETAIL);
state.artifacts.POSE.stale=true;
assert.throws(()=>workflow.validateReferences(state,state.artifacts.DETAIL),/stale/);
state.artifacts.POSE.stale=false;
state.artifacts.DETAIL.references[0].sha256='wrong';
assert.throws(()=>workflow.validateReferences(state,state.artifacts.DETAIL),/hash/);
state.artifacts.DETAIL.references[0].sha256='pose';
state.artifacts.POSE.qa.hard_fail=['头颈错误'];
assert.throws(()=>workflow.ready(state,'detail'),/QA/);
state.artifacts.POSE.qa.hard_fail=[];
state.artifacts.DETAIL.references.push({id:'MISSING',role:'design_anchor',sha256:'none'});
assert.throws(()=>workflow.validateReferences(state,state.artifacts.DETAIL),/missing/);
state.artifacts.DETAIL.references.pop();
state.artifacts.DETAIL.qa.structure_check.status='uncertain';
assert.throws(()=>workflow.choose(state,'detail','DETAIL','不能跳过结构判断'),/structure/);
state.artifacts.DETAIL.qa.structure_check.status='pass';
workflow.choose(state,'detail','DETAIL','细化通过');
state.artifacts.POSE_R1={...state.artifacts.POSE,id:'POSE_R1',sha256:'new-pose'};
state.stages.pose.candidates.push('POSE_R1');
workflow.choose(state,'pose','POSE_R1','替换动作');
assert.equal(state.artifacts.DETAIL.stale,true);
assert.equal(state.stages.detail.selection.stale,true);

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const scratch=scratchDirectory(path.join(root,'tests'),'scratch-v2-');
const run=path.join(scratch,'trial');
const cli=(...args)=>spawnSync(process.execPath,[path.join(root,'tools','deliver.mjs'),'--run',run,...args],{cwd:root,encoding:'utf8'});
const recipe={schema_version:2,stage_order:stages,planned_images:7,repair_limit:2,candidates:stages.map((s,i)=>({id:s.toUpperCase(),stage:s,kind:'image',prompt:'fixture prompt '+s,reference_specs:i?[{stage:stages[i-1],role:'edit_target'}]:[]}))};
const recipePath=path.join(scratch,'recipe.json');fs.writeFileSync(recipePath,JSON.stringify(recipe));
let result=cli('init','--recipe',recipePath);assert.equal(result.status,0,result.stderr);
let created=JSON.parse(fs.readFileSync(path.join(run,'project.json'),'utf8'));
assert.equal(created.mode,'review');assert.deepEqual(created.stage_order,stages);
assert.equal(cli('prepare','STRUCTURE').status,1);
assert.equal(cli('init','--recipe',recipePath).status,1,'init must not overwrite');
const qaPath=path.join(scratch,'qa.json');fs.writeFileSync(qaPath,JSON.stringify({hard_fail:[],observations:['fixture only'],manual_retouch:[],structure_check:{status:'pass'}}));
assert.equal(cli('prepare','POSE').status,0);
result=cli('ingest','POSE',path.join(root,'tests','fixtures','pixel.png'));assert.equal(result.status,0,result.stderr);
assert.equal(cli('qa','POSE',qaPath).status,0);
assert.equal(cli('select','pose','POSE','no human evidence').status,1);
const evidence=path.join(scratch,'human.txt');fs.writeFileSync(evidence,'TEST FIXTURE human choice');
assert.equal(cli('select','pose','POSE','fixture evidence',evidence).status,0);
assert.equal(cli('prepare','STRUCTURE').status,0);
created=JSON.parse(fs.readFileSync(path.join(run,'project.json'),'utf8'));
assert.equal(created.artifacts.STRUCTURE.references[0].id,'POSE');
assert.equal(created.artifacts.STRUCTURE.references[0].sha256,created.artifacts.POSE.sha256);
const revisedPrompt=path.join(scratch,'new-prompt.txt');fs.writeFileSync(revisedPrompt,'new ungenerated fixture prompt');
assert.equal(cli('set-prompt','STRUCTURE',revisedPrompt).status,0);
created=JSON.parse(fs.readFileSync(path.join(run,'project.json'),'utf8'));
assert.equal(Boolean(created.artifacts.STRUCTURE.prepared_at),false,'prompt changes must invalidate prepared input snapshot');
assert.equal(cli('prompt','STRUCTURE').status,1,'must prepare the revised prompt again');
assert.equal(cli('prepare','STRUCTURE').status,0);
for(let i=1;i<=3;i++){
 const repairPath=path.join(scratch,`repair-${i}.json`);
 fs.writeFileSync(repairPath,JSON.stringify({id:`POSE_R${i}`,stage:'pose',kind:'image',repair_of:'POSE',prompt:'fixture repair',reference_specs:[]}));
 assert.equal(cli('add',repairPath).status,i<=2?0:1);
}
const outside=spawnSync(process.execPath,[path.join(root,'tools','deliver.mjs'),'--run',path.resolve(root,'..','outside'),'status'],{encoding:'utf8'});
assert.equal(outside.status,1);
const comparison=path.join(run,'comparison.txt');fs.writeFileSync(comparison,'fixture comparison');
created=JSON.parse(fs.readFileSync(path.join(run,'project.json'),'utf8'));
created.imported_comparisons=[{id:'V1_FIXTURE',file:'comparison.txt',sha256:'wrong',source_sha256:'wrong',used_for_generation:false}];
fs.writeFileSync(path.join(run,'project.json'),JSON.stringify(created));
result=cli('verify');
assert.ok(JSON.parse(result.stdout).errors.some(error=>error.includes('Imported comparison')),'imported comparison tampering must be reported');
console.log('PASS: dynamic stages, reference existence/staleness/hashes, all upstream QA, uncertain structure rejection, invalidation, --run isolation, review default, immutable init, preparation snapshot, prompt revision invalidation, repair cap, imported comparison tampering');
